#!/usr/bin/env bash

set -o errexit -o nounset -o pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
export OPENCLAW_BUNDLE_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
export KAGGLE_SYNC_ROOT="$(cd -- "$OPENCLAW_BUNDLE_DIR/.." && pwd)"

if [[ -d /kaggle/working ]]; then
  DEFAULT_WORK_ROOT=/kaggle/working
else
  DEFAULT_WORK_ROOT=/tmp/opencode/openclaw-kaggle
fi

export OPENCLAW_WORK_ROOT="${OPENCLAW_WORK_ROOT:-$DEFAULT_WORK_ROOT}"
export OPENCLAW_RUNTIME_ROOT="${OPENCLAW_RUNTIME_ROOT:-$OPENCLAW_WORK_ROOT/openclaw-runtime}"
export OPENCLAW_HOME="${OPENCLAW_HOME:-$OPENCLAW_RUNTIME_ROOT/home}"
export OPENCLAW_STATE_DIR="${OPENCLAW_STATE_DIR:-$OPENCLAW_RUNTIME_ROOT/state}"
export OPENCLAW_CONFIG_PATH="${OPENCLAW_CONFIG_PATH:-$OPENCLAW_STATE_DIR/openclaw.json}"
export OPENCLAW_WORKSPACE_DIR="${OPENCLAW_WORKSPACE_DIR:-$OPENCLAW_STATE_DIR/workspace}"
export OPENCLAW_TOOLS_DIR="${OPENCLAW_TOOLS_DIR:-$OPENCLAW_WORK_ROOT/openclaw-tools}"
export OPENCLAW_LOG_DIR="${OPENCLAW_LOG_DIR:-$OPENCLAW_WORK_ROOT/openclaw-logs}"
export OPENCLAW_SECURITY_TOOLS_DIR="${OPENCLAW_SECURITY_TOOLS_DIR:-$OPENCLAW_TOOLS_DIR/security}"
export OPENCLAW_SECURITY_STATE_DIR="${OPENCLAW_SECURITY_STATE_DIR:-$OPENCLAW_STATE_DIR/security}"
export OPENCLAW_SECURITY_HOME="${OPENCLAW_SECURITY_HOME:-$OPENCLAW_SECURITY_STATE_DIR/home}"
export OPENCLAW_REPOSITORIES_DIR="${OPENCLAW_REPOSITORIES_DIR:-$OPENCLAW_STATE_DIR/repositories}"
export OPENCLAW_MCP_PYTHON="${OPENCLAW_MCP_PYTHON:-$OPENCLAW_SECURITY_TOOLS_DIR/mcp-venv/bin/python}"
export OPENCLAW_BACKUP_FILE="${OPENCLAW_BACKUP_FILE:-$OPENCLAW_BUNDLE_DIR/backups/openclaw-state.enc}"
export OPENCLAW_BACKUP_MANIFEST="${OPENCLAW_BACKUP_MANIFEST:-$OPENCLAW_BUNDLE_DIR/backups/manifest.json}"
export OPENCLAW_GATEWAY_PORT="${OPENCLAW_GATEWAY_PORT:-18789}"
export OPENCLAW_MODEL_PORT="${OPENCLAW_MODEL_PORT:-8000}"
export OPENCLAW_HEXSTRIKE_PORT="${OPENCLAW_HEXSTRIKE_PORT:-8888}"
export OPENCLAW_MODEL_ID="${OPENCLAW_MODEL_ID:-WhiteRabbitNeo/WhiteRabbitNeo-13B-v1}"
export OPENCLAW_MODEL_ALIAS="${OPENCLAW_MODEL_ALIAS:-WhiteRabbitNeo-13B}"

# Kaggle workers are short-lived. Installing the full Kali/Ubuntu security
# package catalog before the gateway starts can consume the whole startup
# window. Portable binaries and native MCP servers are always installed; set
# this to 0 explicitly when a session needs the additional APT catalog.
if [[ -d /kaggle/working ]]; then
  export OPENCLAW_SKIP_SECURITY_APT="${OPENCLAW_SKIP_SECURITY_APT:-1}"
else
  export OPENCLAW_SKIP_SECURITY_APT="${OPENCLAW_SKIP_SECURITY_APT:-0}"
fi

export HF_HOME="${HF_HOME:-$OPENCLAW_WORK_ROOT/huggingface}"
export HUGGINGFACE_HUB_CACHE="${HUGGINGFACE_HUB_CACHE:-$HF_HOME/hub}"
export TRANSFORMERS_CACHE="${TRANSFORMERS_CACHE:-$HF_HOME/transformers}"
export PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}"
export TOKENIZERS_PARALLELISM=false

export PATH="$OPENCLAW_TOOLS_DIR/node-v24.16.0-linux-x64/bin:$OPENCLAW_TOOLS_DIR/npm/bin:$OPENCLAW_TOOLS_DIR/bin:$PATH"

mkdir -p "$OPENCLAW_RUNTIME_ROOT" "$OPENCLAW_HOME" "$OPENCLAW_STATE_DIR" \
  "$OPENCLAW_WORKSPACE_DIR" "$OPENCLAW_TOOLS_DIR/bin" "$OPENCLAW_LOG_DIR" "$HF_HOME" \
  "$OPENCLAW_SECURITY_STATE_DIR" "$OPENCLAW_SECURITY_HOME" "$OPENCLAW_REPOSITORIES_DIR"
chmod 0700 "$OPENCLAW_RUNTIME_ROOT" "$OPENCLAW_HOME" "$OPENCLAW_STATE_DIR" \
  "$OPENCLAW_WORKSPACE_DIR" "$OPENCLAW_SECURITY_STATE_DIR" "$OPENCLAW_SECURITY_HOME" \
  "$OPENCLAW_REPOSITORIES_DIR"
